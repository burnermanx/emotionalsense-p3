#!/usr/bin/env python3
"""Rasterise the glyphs of the Respect speed label ("AV 2.3") into game/speed_glyphs.c.

The label is drawn by the host over the presented frame (game/speed.c); nothing of the game's art is
used. Glyphs come from Noto Sans CJK Bold (SIL OFL 1.1; the OFL permits embedding rasterised glyphs,
see THIRD_PARTY_NOTICES.md), as 8-bit coverage at 64 px em, trimmed to their bounding box. Run:

    python3 scripts/gen_speed_glyphs.py [path/to/NotoSansCJK-Bold.ttc] > game/speed_glyphs.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/noto-cjk/NotoSansCJK-Bold.ttc"
CHARS = "AV0123456789."
EM = 64

font = ImageFont.truetype(FONT, EM)
asc, desc = font.getmetrics()
base = asc
out = ["/* Generated by scripts/gen_speed_glyphs.py, do not edit. 8-bit coverage, %d px em, Noto Sans CJK Bold," % EM,
       " * SIL OFL 1.1. y is measured from the top of the line (ascent %d). */" % asc,
       '#include "speed_glyphs.h"', ""]
rows = []
digit_h = 0
for c in CHARS:
    im = Image.new("L", (EM * 2, EM * 2), 0)
    ImageDraw.Draw(im).text((EM // 2, 0), c, font=font, fill=255)
    bb = im.getbbox()
    adv = round(font.getlength(c))
    crop = im.crop(bb)
    w, h = crop.size
    if c == "0":
        digit_h = h
    name = "g_%02x" % ord(c)
    data = list(crop.tobytes())
    out.append("static const unsigned char %s[] = {" % name)
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    out.append("};")
    rows.append("    { '%s', %d, %d, %d, %d, %d, %s }," % (c, w, h, adv, bb[0] - EM // 2, bb[1], name))
out.append("")
out.append("const es_glyph es_speed_glyphs[ES_SPEED_NGLYPHS] = {")
out += rows
out.append("};")
out.append("const int es_speed_em = %d;" % EM)
out.append("const int es_speed_ascent = %d;" % asc)
out.append("const int es_speed_digit_h = %d;   /* height of a digit, the scaling reference */" % digit_h)
print("\n".join(out))
