#!/usr/bin/env python3
"""Regenerates game/exit_text.c: the five-language texts of the title screen's exit dialog as 8-bit coverage masks
at twice the 480x272 resolution (the host draws them with a bilinear lookup at any internal scale).
Noto Sans CJK Bold (SIL OFL 1.1), the question in sentence case with wide tracking, YES / NO in capitals, condensed
(the glyphs are squeezed to 80 % in width).  usage: gen_exit_text.py [out.c]   (needs Pillow and the Noto CJK fonts)"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/noto-cjk/NotoSansCJK-Bold.ttc"
LANGS = [  # code, question, yes, no
    ("en", "Quit the game?", "YES", "NO"),
    ("pt-BR", "Sair do jogo?", "SIM", "NÃO"),
    ("es", "¿Salir del juego?", "SÍ", "NO"),
    ("ja", "ゲームを終了しますか？", "はい", "いいえ"),
    ("ko", "게임을 종료하시겠습니까?", "예", "아니요"),
]
S = 2                      # mask pixels per 480x272 unit
Q_SIZE, Q_TRACK = 16.0, 3.0       # question: font size in units, extra letter spacing in units
B_SIZE, B_SQUEEZE, B_TRACK = 20.0, 0.80, 0.4
CANVAS_H = 34              # units


def render(text, size, track, squeeze):
    font = ImageFont.truetype(FONT, int(round(size * S * 4)), index=0)      # 4x supersampled, then reduced
    asc = font.getmetrics()[0]
    cap = font.getbbox("H")[3] - font.getbbox("H")[1]
    pen, glyphs = 0.0, []
    for ch in text:
        glyphs.append((ch, pen))
        pen += (font.getlength(ch) + track * S * 4) * squeeze
    W = int(pen + 8 * S * 4)
    H = CANVAS_H * S * 4
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    base = H // 2 + cap // 2                                               # cap height centred on the canvas
    for ch, x in glyphs:
        g = Image.new("L", (int(font.getlength(ch)) + 16, H), 0)
        ImageDraw.Draw(g).text((4, base - asc), ch, font=font, fill=255)
        g = g.resize((max(1, int(g.width * squeeze)), H), Image.LANCZOS)
        im.paste(g, (int(x), 0), g)
    bbox = im.getbbox()
    im = im.crop((bbox[0], 0, bbox[2], H))
    im = im.resize((max(1, im.width // 4), H // 4), Image.LANCZOS)
    return im


def emit(name, im):
    w, h = im.size
    data = ",".join(str(v) for v in im.tobytes())
    return "static const unsigned char %s[] = {%s};\n" % (name, data), "{ %d, %d, %s }" % (w, h, name)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "game/exit_text.c"
    body = ["/* Generated by scripts/gen_exit_text.py, do not edit. 8-bit coverage masks at 2 pixels per 480x272 unit.\n"
            " * Noto Sans CJK Bold, SIL OFL 1.1. */\n#include \"exit_text.h\"\n\n"]
    rows = []
    for code, q, y, n in LANGS:
        ident = code.replace("-", "_")
        cells = []
        for k, (txt, size, track, sq) in enumerate(((q, Q_SIZE, Q_TRACK, 1.0), (y, B_SIZE, B_TRACK, B_SQUEEZE), (n, B_SIZE, B_TRACK, B_SQUEEZE))):
            arr, cell = emit("t_%s_%d" % (ident, k), render(txt, size, track, sq))
            body.append(arr + "\n")
            cells.append(cell)
        rows.append("    { %s },  /* %s */\n" % (", ".join(cells), code))
    body.append("const es_exit_text es_exit_texts[ES_EXIT_LANGS][3] = {\n" + "".join(rows) + "};\n")
    body.append("const char *const es_exit_lang_codes[ES_EXIT_LANGS] = { %s };\n" % ", ".join('"%s"' % l[0] for l in LANGS))
    open(out, "w").write("".join(body))
    print("wrote", out)


main()
